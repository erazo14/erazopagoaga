export type TranslationKey = keyof typeof translations.en;

function getInitialLanguage(): Language {
  if (typeof window === 'undefined') return 'es';

  const params = new URLSearchParams(window.location.search);
  const lang = params.get('lang');

  if (lang === 'en' || lang === 'es') {
    return lang;
  }
  
  const stored = window.localStorage.getItem('wedding-language');

  if (stored === 'en' || stored === 'es') {
    return stored;
  }

  return 'es';
}

function interpolate(value: string, variables?: Record<string, string | number>) {
  if (!variables) return value;
  return value.replace(/\{\{(\w+)\}\}/g, (_, key: string) => String(variables[key] ?? ''));
}

type I18nContextValue = {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: TranslationKey, variables?: Record<string, string | number>) => string;
  guestLabel: (count: number) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(getInitialLanguage);

  useEffect(() => {
    window.localStorage.setItem('wedding-language', language);
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo<I18nContextValue>(() => ({
    language,
    setLanguage,
    t: (key, variables) => interpolate(translations[language][key], variables),
    guestLabel: (count) => translations[language][count === 1 ? 'guest.one' : 'guest.many'],
  }), [language]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) throw new Error('useI18n must be used inside I18nProvider');
  return context;
}
